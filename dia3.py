#Haz un programa que pida al usuario 2 numeros y mostrar la suma, mul, div y la resta
num1=int(input("Digite el primer numero: "))
num2=int(input("Digite el segundo numero: "))

print(f"La suma es igual a: {num1 + num2}")
print(f"La resta es igual a: {num1 - num2}")
print(f"La division es igual a: {num1 / num2}")
print(f"La multiplicacion es igual a: {num1 * num2}")